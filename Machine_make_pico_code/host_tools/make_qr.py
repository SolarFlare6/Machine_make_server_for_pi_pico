"""
host_tools/make_qr.py

Host utility to render QR pairing codes generated by the Pico W.
Usage:
  1. Generate QR directly from a payload string:
       python host_tools/make_qr.py --payload '{"protocol":"DCP",...}'

  2. Listen directly to Pico W serial COM port for "QR_PAYLOAD:" line:
       python host_tools/make_qr.py --port COM3
"""

import argparse
import json
import sys


def print_qr_terminal(payload_str):
    try:
        import qrcode
    except ImportError:
        print("[!] Package 'qrcode' is required. Install with: pip install qrcode")
        print("Raw payload JSON:\n", payload_str)
        return

    qr = qrcode.QRCode(border=1)
    qr.add_data(payload_str)
    qr.make(fit=True)
    try:
        qr.print_ascii(invert=True)
    except Exception:
        qr.print_ascii(out=sys.stdout, tty=False)


def main():
    parser = argparse.ArgumentParser(description="MachineMake Pico W QR Pairing Generator")
    parser.add_argument("--payload", default=None, help="QR JSON payload string")
    parser.add_argument("--port", default=None, help="Serial COM port of Pico W (e.g. COM3 or /dev/ttyACM0)")
    parser.add_argument("--baud", type=int, default=115200, help="Serial baud rate (default: 115200)")
    args = parser.parse_args()

    if args.payload:
        print("Rendering QR Code for provided payload:\n")
        print_qr_terminal(args.payload)
        return

    if args.port:
        try:
            import serial
        except ImportError:
            print("[!] Package 'pyserial' is required for serial reading. Install with: pip install pyserial")
            return

        print(f"Connecting to Pico W on {args.port} at {args.baud} baud...")
        print("Waiting for QR_PAYLOAD line from Pico W (or reboot the Pico)...")
        ser = serial.Serial(args.port, args.baud, timeout=1.0)
        while True:
            line = ser.readline().decode("utf-8", errors="ignore").strip()
            if line:
                print(line)
            if "QR_PAYLOAD:" in line:
                payload = line.split("QR_PAYLOAD:", 1)[1].strip()
                print("\nFound pairing payload! Rendering QR Code:\n")
                print_qr_terminal(payload)
                break
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
